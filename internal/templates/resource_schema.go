package templates

import (
	"crypto/sha256"
	"fmt"
	"regexp"
	"strings"
)

// SchemaField is the database contract for a writable resource field.
type SchemaField struct {
	Name      string
	Type      string
	MaxLength int
}

var schemaIdentifier = regexp.MustCompile(`^[a-z][a-z0-9]*(?:_[a-z0-9]+)*$`)

// RenderResourceSchema renders reviewed schema inputs, never executes SQL.
// The returned store only verifies schema; CRUD is a separate rendering step.
func RenderResourceSchema(project Project, database, table string, fields []SchemaField) (File, []byte, error) {
	if database != "sqlite" && database != "mysql" && database != "postgres" {
		return File{}, nil, fmt.Errorf("resource schema requires a SQL database")
	}
	if !schemaIdentifier.MatchString(table) || len(table) > 63 || table == "examples" || table == "casbin_rules" || table == "goose_db_version" {
		return File{}, nil, fmt.Errorf("invalid resource table %q", table)
	}
	if !namePattern.MatchString(project.Name) || !modulePattern.MatchString(project.Module) {
		return File{}, nil, fmt.Errorf("invalid project name or module path")
	}
	for _, part := range strings.Split(project.Module, "/") {
		if part == "." || part == ".." || strings.HasSuffix(part, ".") {
			return File{}, nil, fmt.Errorf("invalid module path segment")
		}
	}
	if len(fields) < 1 || len(fields) > 32 {
		return File{}, nil, fmt.Errorf("resource schema requires 1 to 32 fields")
	}
	seen := map[string]bool{"id": true, "owner": true, "created_at": true, "updated_at": true}
	for _, field := range fields {
		if !schemaIdentifier.MatchString(field.Name) || len(field.Name) > 63 || seen[field.Name] {
			return File{}, nil, fmt.Errorf("invalid resource schema field %q", field.Name)
		}
		seen[field.Name] = true
		if field.Type == "string" {
			if field.MaxLength < 1 || field.MaxLength > 4096 {
				return File{}, nil, fmt.Errorf("invalid string length")
			}
		} else if (field.Type != "bool" && field.Type != "int64") || field.MaxLength != 0 {
			return File{}, nil, fmt.Errorf("invalid field type or length")
		}
	}
	quote := func(name string) string { return `"` + name + `"` }
	if database == "mysql" {
		quote = func(name string) string { return "`" + name + "`" }
	}
	lengthName := func(field string) string {
		digest := sha256.Sum256([]byte(table + "." + field))
		return fmt.Sprintf("gs_%x_len", digest[:16])
	}
	// Fixed short names are also recomputed by the runtime's read-only checker.
	var sql strings.Builder
	fmt.Fprintf(&sql, "-- Review before explicit migrate up; generation does not apply SQL.\n-- +goose Up\nCREATE TABLE %s (\n", quote(table))
	var columns []string
	switch database {
	case "sqlite":
		columns = []string{`"id" INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT`, `"owner" TEXT NOT NULL`, `"created_at" DATETIME NOT NULL`, `"updated_at" DATETIME NOT NULL`}
	case "mysql":
		columns = []string{"`id` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY", "`owner` VARCHAR(128) NOT NULL", "`created_at` DATETIME(6) NOT NULL", "`updated_at` DATETIME(6) NOT NULL"}
	case "postgres":
		columns = []string{`"id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY`, `"owner" VARCHAR(128) COLLATE "C" NOT NULL`, `"created_at" TIMESTAMPTZ NOT NULL`, `"updated_at" TIMESTAMPTZ NOT NULL`}
	}
	all := append([]SchemaField{{Name: "owner", Type: "string", MaxLength: 128}}, fields...)
	for _, field := range fields {
		typeName := "BIGINT"
		if field.Type == "bool" {
			typeName = "BOOLEAN"
		}
		if field.Type == "string" {
			typeName = "TEXT"
			if database == "postgres" {
				typeName = fmt.Sprintf("VARCHAR(%d)", field.MaxLength)
			}
		}
		columns = append(columns, quote(field.Name)+" "+typeName+" NOT NULL")
	}
	for _, field := range all {
		if field.Type == "string" && (database == "sqlite" || (database == "mysql" && field.Name != "owner")) {
			function := "length"
			if database == "mysql" {
				function = "CHAR_LENGTH"
			}
			columns = append(columns, fmt.Sprintf("CONSTRAINT %s CHECK (%s(%s) <= %d)", quote(lengthName(field.Name)), function, quote(field.Name), field.MaxLength))
		}
	}
	sql.WriteString("    " + strings.Join(columns, ",\n    ") + "\n)")
	if database == "mysql" {
		sql.WriteString(" ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin")
	}
	sql.WriteString(";\n")
	digest := sha256.Sum256([]byte(table))
	index := fmt.Sprintf("gs_%x_owner", digest[:16])
	fmt.Fprintf(&sql, "CREATE INDEX %s ON %s (%s, %s);\n\n-- +goose Down\nDROP TABLE %s;\n", quote(index), quote(table), quote("owner"), quote("id"), quote(table))
	var source strings.Builder
	fmt.Fprintf(&source, "package %s\nimport(\"context\";database %q;\"gorm.io/gorm\")\ntype Store struct{db *gorm.DB}\nfunc New(db *gorm.DB)*Store{return &Store{db:db}}\nfunc(s *Store)CheckSchema(ctx context.Context)error{return database.CheckResourceSchema(ctx,s.db,%q,[]database.SchemaField{\n", table, project.Module+"/internal/pkg/database", table)
	for _, field := range fields {
		fmt.Fprintf(&source, "{Name:%q,Type:%q,MaxLength:%d},\n", field.Name, field.Type, field.MaxLength)
	}
	source.WriteString("})}\n")
	formatted, err := formatGo(source.String())
	if err != nil {
		return File{}, nil, err
	}
	return File{Path: "internal/apiserver/store/" + table + "/store.go", Content: formatted}, []byte(sql.String()), nil
}
